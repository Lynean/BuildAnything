def _c_value(field: dict[str, Any], source: str) -> str:
    kind = field["type"]
    if kind == "float32":
        return f"ba_from_f32({source})"
    if kind == "float64":
        return f"ba_from_f64({source})"
    return f"(uint64_t){source}"


def _c_read(field: dict[str, Any], at: str, big: int) -> str:
    kind = field["type"]
    size = (INT_SIZES | FLOAT_SIZES)[kind]
    raw = f"ba_get(in + {at}, {size}, {big})"
    if kind == "float32":
        return f"ba_to_f32((uint32_t){raw})"
    if kind == "float64":
        return f"ba_to_f64({raw})"
    return f"({C_TYPES[kind]}){raw}"


def _int_limits(kind: str) -> tuple[int | None, int | None]:
    if not is_int(kind):
        return None, None
    bits = INT_SIZES[kind] * 8
    return (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if kind.startswith("int") else (0, (1 << bits) - 1)


def _c_checks(field: dict[str, Any], value: str) -> list[str]:
    out = []
    kind = field["type"]
    for check in _checks(field):
        if check[0] == "enum":
            allowed = " || ".join(f"{value} == {v}" for v in check[1])
            out.append(f"    if (!({allowed})) return BA_ERR_RANGE;")
        else:
            _, low, high, sentinel = check
            floor, top = _int_limits(kind)
            parts = []
            if low is not None and (floor is None or low > floor):
                parts.append(f"{value} >= {_c_number(kind, low)}")
            if high is not None and (top is None or high < top):
                parts.append(f"{value} <= {_c_number(kind, high)}")
            if not parts:  # The limits cover the whole type, and compilers reject always-true tests.
                continue
            test = " && ".join(parts)
            guard = f"{value} != {_c_number(kind, sentinel)} && " if sentinel is not None else ""
            out.append(f"    if ({guard}!({test})) return BA_ERR_RANGE;")
    return out


def _c_packet(packet: dict[str, Any]) -> str:
    name, low = packet["name"], packet["name"].lower()
    big = 1 if packet.get("endianness") == "big" else 0
    prefix = f"ba_{low}"
    macro = f"BA_{name}"
    lines = [f"/* {name}, version {packet['version']} */", f"#define {macro}_ID {packet['id']}", f"#define {macro}_VERSION {packet['major']}", f"#define {macro}_{'MIN_SIZE' if packet['variable'] else 'SIZE'} {packet['fixed_size']}"]
    for f in packet["wire"]:
        for label, value in (f.get("enum") or {}).items():
            lines.append(f"#define {macro}_{f['name'].upper()}_{label} {value}")
    members, sizes = [], []
    var = next((f for f in packet["wire"] if f["type"] == "var_bytes"), None)
    if var:
        lines.append(f"#define {macro}_MAX_{var['name'].upper()} {var['max']}")
    for f in payload(packet):
        kind = f["type"]
        count = fixed_bytes(kind)
        if count is not None:
            members.append(f"    uint8_t {f['name']}[{count}];")
            sizes.append(f"sizeof((({prefix}_t *)0)->{f['name']})")
        elif kind == "var_bytes":
            members.append(f"    uint16_t {f['name']}_len;")
            members.append(f"    uint8_t {f['name']}[{f['max']}];")
        else:
            members.append(f"    {C_TYPES[kind]} {f['name']};")
            sizes.append(f"sizeof((({prefix}_t *)0)->{f['name']})")
    if not members:
        members.append("    uint8_t _unused;")
    lines += ["", "typedef struct {", *members, f"}} {prefix}_t;", ""]
    constants = sum(_wire_size(f) for f in packet["wire"] if "const" in f) + (2 if packet.get("checksum") else 0) + (2 if var else 0)
    total = " + ".join(sizes + [str(constants)])
    size_macro = f"{macro}_{'MIN_SIZE' if var else 'SIZE'}"
    lines += [f'BA_STATIC_ASSERT({total} == {size_macro}, "{name}: field sizes don\'t add up to the defined size.");', ""]

    # Encoder
    lines += ["/* Returns the number of bytes written, or 0 if it doesn't fit. */", f"static inline size_t {prefix}_encode(const {prefix}_t *m, uint8_t *out, size_t capacity) {{"]
    lines.append("    size_t i = 0;")
    lines.append("    (void)m;  /* A message with no fields doesn't read it. */")
    if var:
        lines.append(f"    if (m->{var['name']}_len > {var['max']}) return 0;")
        lines.append(f"    if (capacity < (size_t){size_macro} + m->{var['name']}_len) return 0;")
    else:
        lines.append(f"    if (capacity < {size_macro}) return 0;")
    for f in packet["wire"]:
        kind = f["type"]
        count = fixed_bytes(kind)
        if "const" in f:
            size = _wire_size(f)
            value = _c_number(kind, f["const"]) if is_int(kind) else str(f["const"])
            lines.append(f"    ba_put(out + i, (uint64_t){value}, {size}, {big}); i += {size};")
        elif count is not None:
            lines.append(f"    memcpy(out + i, m->{f['name']}, {count}); i += {count};")
        elif kind == "var_bytes":
            lines.append(f"    ba_put(out + i, m->{f['name']}_len, 2, {big}); i += 2;")
            lines.append(f"    memcpy(out + i, m->{f['name']}, m->{f['name']}_len); i += m->{f['name']}_len;")
        else:
            size = (INT_SIZES | FLOAT_SIZES)[kind]
            lines.append(f"    ba_put(out + i, {_c_value(f, 'm->' + f['name'])}, {size}, {big}); i += {size};")
    if packet.get("checksum"):
        lines.append(f"    {{ uint16_t crc = ba_crc16(out, i); ba_put(out + i, crc, 2, {big}); i += 2; }}")
    lines += ["    return i;", "}", ""]

    # Decoder
    lines += [f"static inline ba_result_t {prefix}_decode(const uint8_t *in, size_t length, {prefix}_t *m) {{"]
    lines.append("    (void)m;")
    if packet["header_size"]:
        lines.append(f"    if (length < {packet['header_size']}) return BA_ERR_SIZE;")
    lines += []
    if not packet.get("raw"):
        lines += [f"    if (in[0] != {macro}_ID) return BA_ERR_TYPE;", f"    if (in[1] != {packet['major'] % 256}) return BA_ERR_VERSION;"]
    if var:
        lines += [f"    if (length < {size_macro}) return BA_ERR_SIZE;", f"    uint16_t var_length = (uint16_t)ba_get(in + {var['offset']}, 2, {big});", f"    if (var_length > {var['max']}) return BA_ERR_RANGE;", f"    if (length != (size_t){size_macro} + var_length) return BA_ERR_SIZE;"]
    else:
        lines.append(f"    if (length != {size_macro}) return BA_ERR_SIZE;")
    if packet.get("checksum"):
        lines.append(f"    if (ba_get(in + length - 2, 2, {big}) != ba_crc16(in, length - 2)) return BA_ERR_CHECKSUM;")
    for f in packet["wire"]:
        kind, at = f["type"], f["offset"]
        count = fixed_bytes(kind)
        if "const" in f:
            lines.append(f"    if (ba_get(in + {at}, {_wire_size(f)}, {big}) != (uint64_t){_c_number(kind, f['const'])}) return BA_ERR_CONST;")
        elif count is not None:
            lines.append(f"    memcpy(m->{f['name']}, in + {at}, {count});")
        elif kind == "var_bytes":
            lines.append(f"    m->{f['name']}_len = var_length;")
            lines.append(f"    memcpy(m->{f['name']}, in + {at} + 2, var_length);")
        else:
            lines.append(f"    m->{f['name']} = {_c_read(f, str(at), big)};")
            lines += _c_checks(f, f"m->{f['name']}")
    lines += ["    return BA_OK;", "}", ""]
    return "\n".join(lines)


def _wire_size(field: dict[str, Any]) -> int:
    kind = field["type"]
    count = fixed_bytes(kind)
    if count is not None:
        return count
    return 0 if kind == "var_bytes" else (INT_SIZES | FLOAT_SIZES)[kind]


C_SERIAL = '''/* Over a serial link, one packet is one text line: "@pkt <hex>" and a newline. Log lines never start with @pkt. */
static inline size_t ba_serial_frame(const uint8_t *data, size_t len, char *out, size_t cap) {
  static const char digits[] = "0123456789abcdef";
  size_t used = 0;
  if (cap < 5 + len * 2 + 2) return 0;
  out[used++] = '@'; out[used++] = 'p'; out[used++] = 'k'; out[used++] = 't'; out[used++] = ' ';
  for (size_t i = 0; i < len; i++) { out[used++] = digits[data[i] >> 4]; out[used++] = digits[data[i] & 15]; }
  out[used++] = '\\n';
  out[used] = 0;
  return used;
}

static inline int ba_serial_nibble(char c) {
  if (c >= '0' && c <= '9') return c - '0';
  if (c >= 'a' && c <= 'f') return c - 'a' + 10;
  if (c >= 'A' && c <= 'F') return c - 'A' + 10;
  return -1;
}

/* Returns the packet's length in bytes, or 0 if this line isn't a packet. */
static inline size_t ba_serial_unframe(const char *line, uint8_t *out, size_t cap) {
  size_t count = 0;
  if (line[0] != '@' || line[1] != 'p' || line[2] != 'k' || line[3] != 't' || line[4] != ' ') return 0;
  line += 5;
  while (line[0] && line[0] != '\\n' && line[0] != '\\r') {
    int high = ba_serial_nibble(line[0]);
    int low = line[1] ? ba_serial_nibble(line[1]) : -1;
    if (high < 0 || low < 0 || count >= cap) return 0;
    out[count++] = (uint8_t)(high * 16 + low);
    line += 2;
  }
  return count;
}
'''


def generate_c(packets: list[dict[str, Any]]) -> str:
    body = "\n".join(_c_packet(p) for p in packets)
    f64 = any(f.get("type") == "float64" for p in packets for f in p.get("wire", []))
    prelude = C_PRELUDE.replace("%F64%", C_F64 if f64 else "")
    return f"/* {BANNER} */\n{prelude}\n{C_SERIAL}\n{body}\n#endif\n"


