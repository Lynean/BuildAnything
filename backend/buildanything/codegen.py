"""Packet code generator. It is deterministic, so no AI writes wire formats.

C, Python and TypeScript all come from one definition. See interfaces.wire() for the byte layout.
Decoders report one of: size, type, version, checksum, const, range.
"""
from __future__ import annotations

import json
import re
from typing import Any

BANNER = "Generated by BuildAnything from the project's interface definitions. Do not edit. Change the definition on the Interface screen."

INT_SIZES = {"uint8": 1, "uint16": 2, "uint32": 4, "uint64": 8, "int8": 1, "int16": 2, "int32": 4, "int64": 8, "enum8": 1}
FLOAT_SIZES = {"float32": 4, "float64": 8}
C_TYPES = {"uint8": "uint8_t", "uint16": "uint16_t", "uint32": "uint32_t", "uint64": "uint64_t", "int8": "int8_t", "int16": "int16_t", "int32": "int32_t", "int64": "int64_t", "enum8": "uint8_t", "float32": "float", "float64": "double"}
STRUCT = {"uint8": "B", "uint16": "H", "uint32": "I", "uint64": "Q", "int8": "b", "int16": "h", "int32": "i", "int64": "q", "enum8": "B", "float32": "f", "float64": "d"}
VIEW = {"uint8": "Uint8", "uint16": "Uint16", "uint32": "Uint32", "uint64": "BigUint64", "int8": "Int8", "int16": "Int16", "int32": "Int32", "int64": "BigInt64", "enum8": "Uint8", "float32": "Float32", "float64": "Float64"}
BYTES = re.compile(r"^bytes\[(\d+)\]$")
STATUS = ["ok", "size", "type", "version", "checksum", "const", "range"]


def fixed_bytes(kind: str) -> int | None:
    match = BYTES.match(kind)
    return int(match.group(1)) if match else None


def is_int(kind: str) -> bool:
    return kind in INT_SIZES


def is_float(kind: str) -> bool:
    return kind in FLOAT_SIZES


def class_name(name: str) -> str:
    return "".join(part.capitalize() for part in name.lower().split("_"))


def _literal(value: Any) -> str:
    if isinstance(value, float):
        return repr(value)
    return str(value)


def _c_number(kind: str, value: Any) -> str:
    if is_float(kind):
        return f"{float(value)!r}" + ("f" if kind == "float32" else "")
    if kind == "uint64":
        return f"{int(value)}ULL"
    if kind == "int64":
        return f"(INT64_C({int(value)}))"
    return str(int(value))


def payload(packet: dict[str, Any]) -> list[dict[str, Any]]:
    """Fields a program sets. Constants are written and checked by the generated code."""
    return [f for f in packet["wire"] if "const" not in f]


def _checks(field: dict[str, Any]) -> list[str]:
    """Each is a Python-style condition on the value 'v' that must hold."""
    out = []
    if field.get("enum"):
        out.append(("enum", sorted(field["enum"].values())))
    if field.get("min") is not None or field.get("max") is not None:
        out.append(("range", field.get("min"), field.get("max"), field.get("sentinel")))
    return out


