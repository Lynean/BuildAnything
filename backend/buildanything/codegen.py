TS_PRELUDE = """export class PacketError extends Error {
  status: string;
  constructor(status: string) {
    super(status);
    this.status = status;
  }
}

export function crc16(data: Uint8Array): number {
  let crc = 0xffff;
  for (const byte of data) {
    crc ^= byte << 8;
    for (let bit = 0; bit < 8; bit++) crc = crc & 0x8000 ? ((crc << 1) ^ 0x1021) & 0xffff : (crc << 1) & 0xffff;
  }
  return crc;
}

/** Rebuilds a chunked transfer. Partial data is never returned, and a finished transfer ID can't run twice. */
export class Reassembler {
  chunkSize: number;
  transferId: number | null = null;
  count = 0;
  parts = new Map<number, Uint8Array>();
  finished = new Set<number>();
  constructor(chunkSize: number) {
    this.chunkSize = chunkSize;
  }
  add(transferId: number, index: number, count: number, data: Uint8Array): Uint8Array | null {
    if (count === 0 || index >= count || this.finished.has(transferId) || data.length > this.chunkSize || (index + 1 < count && data.length !== this.chunkSize)) throw new PacketError("range");
    if (transferId !== this.transferId) {
      this.transferId = transferId;
      this.count = count;
      this.parts = new Map();
    }
    if (count !== this.count) throw new PacketError("range");
    if (!this.parts.has(index)) this.parts.set(index, data.slice());
    if (this.parts.size < this.count) return null;
    this.finished.add(transferId);
    this.transferId = null;
    const total = [...this.parts.values()].reduce((n, part) => n + part.length, 0);
    const out = new Uint8Array(total);
    let at = 0;
    for (let i = 0; i < count; i++) {
      const part = this.parts.get(i) as Uint8Array;
      out.set(part, at);
      at += part.length;
    }
    return out;
  }
}
"""


def _ts_hint(field: dict[str, Any]) -> str:
    kind = field["type"]
    if fixed_bytes(kind) is not None or kind == "var_bytes":
        return "Uint8Array"
    return "bigint" if kind in ("uint64", "int64") else "number"


def _ts_number(kind: str, value: Any) -> str:
    return f"{int(value)}n" if kind in ("uint64", "int64") else _literal(value)


def _ts_checks(field: dict[str, Any], value: str) -> list[str]:
    out = []
    kind = field["type"]
    for check in _checks(field):
        if check[0] == "enum":
            allowed = ", ".join(_ts_number(kind, v) for v in check[1])
            out.append(f'  if (![{allowed}].includes({value})) throw new PacketError("range");')
        else:
            _, low, high, sentinel = check
            parts = []
            if low is not None:
                parts.append(f"{value} >= {_ts_number(kind, low)}")
            if high is not None:
                parts.append(f"{value} <= {_ts_number(kind, high)}")
            guard = f"{value} !== {_ts_number(kind, sentinel)} && " if sentinel is not None else ""
            out.append(f'  if ({guard}!({" && ".join(parts)})) throw new PacketError("range");')
    return out


def _ts_packet(packet: dict[str, Any]) -> str:
    cls = class_name(packet["name"])
    little = "false" if packet.get("endianness") == "big" else "true"
    size_key = "MIN_SIZE" if packet["variable"] else "SIZE"
    lines = ["", f"/** {packet['name']}, version {packet['version']}. */", f"export const {packet['name']}_ID = {packet['id']};", f"export const {packet['name']}_VERSION = {packet['major']};", f"export const {packet['name']}_{size_key} = {packet['fixed_size']};"]
    for f in packet["wire"]:
        if f.get("enum"):
            lines.append(f"export const {packet['name']}_{f['name'].upper()} = {json.dumps(f['enum'])} as const;")
    lines.append(f"export interface {cls} {{")
    for f in payload(packet):
        lines.append(f"  {f['name']}: {_ts_hint(f)};")
    lines += ["}", ""]
    var = next((f for f in packet["wire"] if f["type"] == "var_bytes"), None)
    param = "m" if payload(packet) else "_m"
    lines.append(f"export function encode{cls}({param}: {cls}): Uint8Array {{")
    if var:
        lines += [f'  if (m.{var["name"]}.length > {var["max"]}) throw new PacketError("range");', f"  const out = new Uint8Array({packet['fixed_size']} + m.{var['name']}.length);"]
    else:
        lines.append(f"  const out = new Uint8Array({packet['fixed_size']});")
    lines.append("  const view = new DataView(out.buffer);")
    lines.append("  let i = 0;")
    for f in packet["wire"]:
        kind = f["type"]
        count = fixed_bytes(kind)
        if "const" in f:
            lines.append(f"  view.set{VIEW[kind]}(i, {_ts_number(kind, f['const'])}, {little}); i += {_wire_size(f)};")
        elif count is not None:
            lines += [f'  if (m.{f["name"]}.length !== {count}) throw new PacketError("size");', f"  out.set(m.{f['name']}, i); i += {count};"]
        elif kind == "var_bytes":
            lines.append(f"  view.setUint16(i, m.{f['name']}.length, {little}); i += 2;")
            lines.append(f"  out.set(m.{f['name']}, i); i += m.{f['name']}.length;")
        else:
            lines.append(f"  view.set{VIEW[kind]}(i, m.{f['name']}, {little}); i += {_wire_size(f)};")
    if packet.get("checksum"):
        lines.append(f"  view.setUint16(i, crc16(out.subarray(0, i)), {little});")
    lines += ["  return out;", "}", ""]
    lines += [f"export function decode{cls}(data: Uint8Array): {cls} {{", "  const view = new DataView(data.buffer, data.byteOffset, data.byteLength);", f'  if (data.length < {packet["header_size"]}) throw new PacketError("size");']
    if not packet.get("raw"):
        lines += [f'  if (data[0] !== {packet["id"]}) throw new PacketError("type");', f'  if (data[1] !== {packet["major"] % 256}) throw new PacketError("version");']
    if var:
        lines += [f'  if (data.length < {packet["fixed_size"]}) throw new PacketError("size");', f"  const varLength = view.getUint16({var['offset']}, {little});", f'  if (varLength > {var["max"]}) throw new PacketError("range");', f'  if (data.length !== {packet["fixed_size"]} + varLength) throw new PacketError("size");']
    else:
        lines.append(f'  if (data.length !== {packet["fixed_size"]}) throw new PacketError("size");')
    if packet.get("checksum"):
        lines.append(f'  if (view.getUint16(data.length - 2, {little}) !== crc16(data.subarray(0, data.length - 2))) throw new PacketError("checksum");')
    names = []
    for f in packet["wire"]:
        kind, at = f["type"], f["offset"]
        count = fixed_bytes(kind)
        if "const" in f:
            lines.append(f'  if (view.get{VIEW[kind]}({at}, {little}) !== {_ts_number(kind, f["const"])}) throw new PacketError("const");')
        elif count is not None:
            lines.append(f"  const {f['name']} = data.slice({at}, {at + count});")
            names.append(f["name"])
        elif kind == "var_bytes":
            lines.append(f"  const {f['name']} = data.slice({at + 2}, {at + 2} + varLength);")
            names.append(f["name"])
        else:
            lines.append(f"  const {f['name']} = view.get{VIEW[kind]}({at}, {little});")
            lines += _ts_checks(f, f["name"])
            names.append(f["name"])
    lines += ["  return { " + ", ".join(names) + " };", "}"]
    return "\n".join(lines)


