def scan_workspace(root: Path, device: str, valid_notes: set[str] | None = None, known_components: set[str] | None = None) -> list[dict[str, Any]]:
    base = root / "firmware" / device
    out = []
    if not base.exists():
        return out
    for path in sorted(p for p in base.rglob("*") if p.is_file() and p.suffix in (".c", ".cpp", ".h", ".ino", *HOST_SUFFIXES) and ".pio" not in p.parts and "node_modules" not in p.parts):
        relative = path.relative_to(base).as_posix()
        text = path.read_text(encoding="utf-8", errors="replace")
        if GENERATED_MARK in text[:300] or PIN_MARK in text[:300] or ROBOT_MARK in text[:300]:
            out.append({"path": relative, "blocks": [], "plain": text, "outside": "", "generated": True})
            continue
        parsed = parse(text)
        if valid_notes is not None:
            for block in parsed["blocks"]:
                cited = [b[5:] for b in block.get("based_on", []) if b.startswith("note:")]
                if block["state"] == "documented" and any(c not in valid_notes for c in cited):
                    block["state"] = "source_changed"
        if known_components is not None:
            wanted = {k.lower() for k in known_components}
            for block in parsed["blocks"]:
                if block["state"] == "documented" and any(c.lower() not in wanted for c in block.get("components", [])):
                    block["state"] = "source_changed"
        out.append({"path": relative, "blocks": parsed["blocks"], "plain": None if parsed["blocks"] else text, "outside": parsed["outside"], "generated": False})
    return out


_catalog: dict[str, dict[str, Any]] | None = None


def board_catalog() -> dict[str, dict[str, Any]]:
    """Every board PlatformIO knows. Empty if PlatformIO isn't available."""
    global _catalog
    if _catalog:
        return _catalog
    info = conn.detect_cli("pio")
    if not info["found"]:
        return {}
    try:
        done = subprocess.run([info["path"], "boards", "--json-output"], capture_output=True, text=True, timeout=120, env=conn.clean_environment())
        boards = json.loads(done.stdout)
    except (OSError, subprocess.SubprocessError, ValueError):
        return {}
    _catalog = {}
    for b in boards:
        frameworks = b.get("frameworks") or []
        if frameworks:
            _catalog[b["id"]] = {"id": b["id"], "name": b["name"], "mcu": b.get("mcu", ""), "platform": b["platform"], "framework": "arduino" if "arduino" in frameworks else frameworks[0]}
    return _catalog


def find_board(board: str) -> dict[str, Any] | None:
    return board_catalog().get(board)


def search_boards(query: str, limit: int = 40) -> list[dict[str, Any]]:
    words = query.lower().split()
    found = [b for b in board_catalog().values() if all(w in f"{b['id']} {b['name']} {b['mcu']}".lower() for w in words)]
    return sorted(found, key=lambda b: (b["framework"] != "arduino", len(b["name"]), b["name"]))[:limit]


def device_config(root: Path, device: str) -> dict[str, str] | None:
    path = root / "firmware" / device / "platformio.ini"
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    values = dict(re.findall(r"^(platform|board|framework)\s*=\s*(\S+)", text, re.M))
    return {"board": values.get("board", ""), "platform": values.get("platform", "espressif32"), "framework": values.get("framework", "arduino")}


def _read_libraries(base: Path) -> list[str]:
    path = base / "platformio.ini"
    match = re.search(r"^lib_deps\s*=\s*\n((?:[ \t]+\S.*(?:\n|$))+)", path.read_text(encoding="utf-8"), re.M) if path.exists() else None
    return [line.strip() for line in match.group(1).splitlines() if line.strip()] if match else []


def _libraries_section(libraries: list[str]) -> str:
    return "lib_deps =\n" + "".join(f"    {name}\n" for name in libraries) if libraries else ""


def set_libraries(root: Path, device: str, libraries: list[str]) -> None:
    """Only plain library names reach the build file."""
    wanted = list(dict.fromkeys(name.strip() for name in libraries if re.fullmatch(r"[\w@/ .^~-]{1,120}", name.strip())))
    path = root / "firmware" / device / "platformio.ini"
    text = re.sub(r"^lib_deps\s*=\s*\n(?:[ \t]+\S.*(?:\n|$))+", "", path.read_text(encoding="utf-8"), flags=re.M)
    path.write_text(text.rstrip("\n") + "\n" + _libraries_section(wanted), encoding="utf-8", newline="\n")
    if "ststm32" in text and any("ST7735" in name for name in wanted):
        # Adafruit's display library includes an Arduino header that the STM32 core doesn't have, and doesn't use anything from it.
        shim = root / "firmware" / device / "lib" / "wiring_private" / "wiring_private.h"
        shim.parent.mkdir(parents=True, exist_ok=True)
        shim.write_text(SHIM_TEXT, encoding="utf-8", newline="\n")


def written_before_output(code: str) -> list[str]:
    """Pins written before pinMode makes them outputs. On STM32 that write is lost and the pin starts LOW."""
    out = []
    for name in sorted(set(re.findall(r"digitalWrite\s*\(\s*(BA_PIN_\w+)", code))):
        write = re.search(r"digitalWrite\s*\(\s*" + name + r"\b", code)
        mode = re.search(r"pinMode\s*\(\s*" + name + r"\b", code)
        if mode and write.start() < mode.start():
            out.append(name)
    return out


def switched_off(code: str, settings: str = "") -> list[str]:
    """Compile-time switches that default to off and hide code that drives real pins."""
    out = []
    for name in sorted(set(re.findall(r"^\s*#\s*define\s+(\w+)\s+0\s*$", code, re.M))):
        if f"-D{name}" in settings:
            continue
        for start in re.finditer(rf"^\s*#\s*if\s+{name}\b.*$", code, re.M):
            end = re.search(r"^\s*#\s*(?:endif|else)\b", code[start.end():], re.M)
            if "BA_PIN_" in code[start.end():start.end() + end.start() if end else len(code)]:
                out.append(name)
                break
    return out


def write_platformio(root: Path, device: str, board: str, flags: str = "") -> None:
    catalog = board_catalog()
    if catalog and board not in catalog:
        raise ValueError(f"{board} isn't a known board.")
    info = catalog.get(board) or {"platform": "espressif32", "framework": "arduino"}
    base = root / "firmware" / device
    base.mkdir(parents=True, exist_ok=True)
    speed = "upload_speed = 230400\n" if info["platform"] == "espressif32" else ""  # Cheap USB adapters failed at higher speeds in testing.
    build_flags = f"build_flags = {flags}\n" if flags else ""
    libraries = _libraries_section(_read_libraries(base))  # Rewriting the settings for a board mustn't lose what the code needs.
    (base / "platformio.ini").write_text(f"[env:device]\nplatform = {info['platform']}\nboard = {board}\nframework = {info['framework']}\nmonitor_speed = 115200\n{speed}{build_flags}{libraries}", encoding="utf-8", newline="\n")
    (base / ".gitignore").write_text(".pio/\n", encoding="utf-8", newline="\n")


def resolve_board(root: Path, device: str, board: str) -> str:
    config = device_config(root, device)
    if board:
        return board
    if config:
        return config["board"]
    raise ValueError("Choose this device's board first, on its Device tab.")


def set_native_usb(root: Path, device: str, native: bool, chip: str) -> None:
    """Boards plugged in through the chip's own USB port need serial output sent there."""
    config = device_config(root, device)
    if config is None:
        return
    flags = ""
    if native:
        flags = "-DARDUINO_USB_CDC_ON_BOOT=1" if chip.upper().replace("-", "") == "ESP32S2" else "-DARDUINO_USB_MODE=1 -DARDUINO_USB_CDC_ON_BOOT=1"
    write_platformio(root, device, config["board"], flags)


def error_lines(output: str, limit: int = 30) -> list[str]:
    """Only the lines that matter go to the model, which protects the budget."""
    hits = [l.strip() for l in output.splitlines() if re.search(r"\berror\b|fatal|undefined reference", l, re.I)]
    return list(dict.fromkeys(hits))[:limit]


_build_locks: dict[str, threading.Lock] = {}
_build_guard = threading.Lock()


def build(root: Path, device: str, timeout: int = 900) -> dict[str, Any]:
    """One build per device at a time: two at once fight over the same output files."""
    with _build_guard:
        lock = _build_locks.setdefault(str(root / "firmware" / device), threading.Lock())
    with lock:
        return _build(root, device, timeout)


def _build(root: Path, device: str, timeout: int = 900) -> dict[str, Any]:
    base = root / "firmware" / device
    info = conn.detect_cli("pio")
    if not info["found"]:
        return {"ok": False, "ran": False, "errors": [], "detail": "PlatformIO isn't connected. Set it up under Connectors."}
    try:
        done = subprocess.run([info["path"], "run"], cwd=base, capture_output=True, text=True, timeout=timeout, env=conn.clean_environment())
    except subprocess.TimeoutExpired:
        return {"ok": False, "ran": True, "errors": ["The build timed out."], "detail": "The build timed out."}
    output = (done.stdout or "") + (done.stderr or "")
    errors = error_lines(output)
    if done.returncode != 0 and not errors:
        # Tool failures don't always say "error". Never report a failed build with no detail.
        errors = [line.strip()[:400] for line in output.splitlines() if line.strip()][-8:]
    return {"ok": done.returncode == 0, "ran": True, "errors": errors, "detail": "Build succeeded." if done.returncode == 0 else "Build failed.", "fingerprint": fingerprint("\n".join(errors)) if errors else None}


def is_computer(root: Path, device: str) -> bool:
    """Devices with a build configuration are boards. Anything else runs on a computer."""
    return (root / "firmware" / device).is_dir() and not (root / "firmware" / device / "platformio.ini").exists()


def limits_text(state: ProjectState) -> str:
    names = {c["id"]: c["fields"]["part_number"] for c in state.of_type("component")}
    rows = []
    for p in state.of_type("parameter", "confirmed"):
        f = p["fields"]
        value = "/".join(str(v) for v in (f.get("min"), f.get("typ"), f.get("max")))
        extra = f" addresses {f['addresses']}" if f.get("addresses") else ""
        rows.append(f"- {names.get(f['component'], '?')} {f['kind']} ({f.get('label')}): {value} {f.get('unit') or ''}{extra}, datasheet p.{f.get('page')}")
    return "\n".join(rows) or "No confirmed limits."


def devices(root: Path) -> list[str]:
    base = root / "firmware"
    return sorted(p.name for p in base.iterdir() if p.is_dir()) if base.exists() else []


def current_code(root: Path, device: str) -> str:
    parts = []
    for file in scan_workspace(root, device):
        body = "\n\n".join(b["code"] for b in file["blocks"]) if file["blocks"] else (file["plain"] or "")
        parts.append(f"--- {file['path']} ---\n{body}")
    return "\n\n".join(parts) or "No files yet."


def valid_note_ids(state: ProjectState) -> set[str]:
    return {n["id"] for n in current_notes(state)}


PIN_HEADER = "include/ba_pins.h"


def pin_defines(state: ProjectState) -> dict[str, str]:
    """Agreed signal pins, from the connection list. One source, so Electrical and code can't disagree."""
    out = {}
    confirmed = state.of_type("net", "confirmed")
    # Until the person confirms the list, code is written against Electrical's draft. Gate 4 still needs it confirmed,
    # and a changed pin then shows as an out-of-date header, so the code is regenerated.
    named = {n["fields"]["name"] for n in confirmed}
    for net in confirmed + [n for n in state.of_type("net", "proposed") if n["fields"]["name"] not in named]:
        if net["fields"]["kind"] in ("power", "ground"):
            continue
        for member in net["fields"]["members"]:
            match = re.fullmatch(r"(?:GPIO|IO)_?(\d+)|(P[A-K]\d{1,2})", str(member["pin"]).strip(), re.I)
            if match:
                out[re.sub(r"[^A-Z0-9]+", "_", net["fields"]["name"].upper()).strip("_")] = match.group(1) or match.group(2).upper()
                break
    return out


def pin_header_text(defines: dict[str, str]) -> str:
    rows = "\n".join(f"#define BA_PIN_{name} {value}" for name, value in sorted(defines.items()))
    return f"/* Generated from the project's agreed connection list. Do not edit. */\n#ifndef BA_PINS_H\n#define BA_PINS_H\n{rows}\n#endif\n"


def write_pins(root: Path, state: ProjectState, device: str) -> None:
    defines = pin_defines(state)
    if defines and not is_computer(root, device):
        target = root / "firmware" / device / PIN_HEADER
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(pin_header_text(defines), encoding="utf-8", newline="\n")


BUILT_IN_LINK = re.compile(r"USART|UART|VCP|SERIAL|ST_?LINK|USB", re.I)  # Reached through the board's own Serial, not by pin number.


def pin_problems(root: Path, state: ProjectState) -> list[str]:
    defines = pin_defines(state)
    if not defines:
        return []
    out = []
    every_board = ""
    boards = [d for d in devices(root) if not is_computer(root, d)]
    for device in devices(root):
        if is_computer(root, device):
            continue
        base = root / "firmware" / device
        header = base / PIN_HEADER
        code = "".join(p.read_text(encoding="utf-8", errors="replace") for p in (base / "src").rglob("*") if p.is_file()) if (base / "src").is_dir() else ""
        if not header.exists() or header.read_text(encoding="utf-8") != pin_header_text(defines) or "ba_pins.h" not in code:
            out.append(f"{device}'s code doesn't use the agreed pin list yet.")
        every_board += code
        settings = (base / "platformio.ini").read_text(encoding="utf-8") if (base / "platformio.ini").exists() else ""
        out += [f"{device}'s code switches part of itself off with {name}, and nothing turns it on. Remove the switch." for name in switched_off(code, settings)]
        out += [f"{device}'s code writes {name} before pinMode makes it an output, so the write is lost. Call pinMode first." for name in written_before_output(code)]
    unused = sorted(name for name in defines if f"BA_PIN_{name}" not in every_board and not BUILT_IN_LINK.search(name))
    if boards and every_board and unused:
        out.append(f"{boards[0]}'s code never uses these agreed pins: {', '.join(unused)}. Every wire the person connected has a job, so use them.")
    return out


PART_SKILLS = Path(__file__).parent / "skills" / "parts"


def _part_skill_files() -> list[tuple[re.Pattern[str], str, str]]:
    """Each file starts with a match line saying which platforms, boards or parts it's for."""
    out = []
    for path in sorted(PART_SKILLS.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        head, _, body = text.removeprefix("---\n").partition("\n---\n")
        match = next((line.split(":", 1)[1].strip() for line in head.splitlines() if line.startswith("match:")), "")
        if match:
            out.append((re.compile(match, re.I), path.stem, body.strip()))
    return out


def part_skills(*texts: Any) -> str:
    """Only the knowledge for this device's platform, board and parts, so other projects never read it."""
    text = json.dumps(texts, default=str)
    return "\n\n".join(body for pattern, _, body in _part_skill_files() if pattern.search(text))


def part_skill_names(*texts: Any) -> list[str]:
    text = json.dumps(texts, default=str)
    return [name for pattern, name, _ in _part_skill_files() if pattern.search(text)]


LAYERS = ("driver", "mid", "app")
INCLUDE = re.compile(r'^\s*#\s*include\s*[<"]([^>"]+)[>"]', re.M)
RAW_PIN_CALL = re.compile(r"\b(?:BA_PIN_\w+|pinMode|digitalWrite|digitalRead|analogRead|analogWrite|attachInterrupt)\b")


def _layer(path: str) -> str | None:
    parts = path.replace("\\", "/").split("/")
    return next((p for p in parts if p in LAYERS), None)


STUB = re.compile(r"\b(\w+)\s*\([^;{)]*\)\s*\{\s*(?:\(void\)\s*\w+\s*;\s*)+(?:return\s+(?:false|0|NULL|nullptr|-1)\s*;\s*)?\}")


def stubs(code: str) -> list[str]:
    """Functions that only ignore their inputs, then return nothing or a failure."""
    return sorted(set(STUB.findall(code)))


def layer_problems(plan: list[ModulePlan], files: list[FileOut], existing: list[str], pins: dict[str, str], layers: tuple[str, ...] = LAYERS, known: list[ModulePlan] | None = None) -> list[str]:
    """The FIRMWARE skill's layers, checked by code: plan first, includes go down, and only drivers touch pins.
    layers are the ones this call may write. known are modules the other department already planned."""
    problems = []
    paths = {f.path for f in files} | set(existing)
    plan = [m for m in plan if m.layer in layers]  # Modules from the other department's layers are theirs, so they aren't checked here.
    planned = {(m.layer, m.name) for m in plan + (known or [])}
    for m in plan:
        if not any(p.startswith(f"src/{m.layer}/{m.name}.") for p in paths) and not (m.layer == "app" and m.name == "main" and any(p.endswith("main.cpp") for p in paths)):
            problems.append(f"The plan lists {m.layer} module {m.name}, but there's no src/{m.layer}/{m.name}.h or .cpp.")
        below = LAYERS[LAYERS.index(m.layer) - 1] if m.layer != "driver" else None
        for used in m.uses:
            if below is None or (below, used) not in planned:
                problems.append(f"{m.layer} module {m.name} uses {used}, which isn't a {below or 'lower'} module in the plan. Each layer only calls the one below it.")
    for f in files:
        layer = _layer(f.path)
        if f.path not in ("src/main.cpp", "src/app/main.cpp") and (layer is None or not f.path.startswith(f"src/{layer}/")):
            problems.append(f"{f.path} isn't in a layer. Put it in src/driver, src/mid or src/app.")
            continue
        if (layer or "app") not in layers:
            problems.append(f"{f.path} is in the {layer or 'app'} layer, which this step doesn't write. " + ("Software writes the app on top of your middleware." if "app" not in layers else "Electrical owns the drivers and middleware. Use them as they are, or ask Electrical."))
            continue
        if f.path.endswith(".h") and layer in ("driver", "mid") and (layer, f.path.rsplit("/", 1)[-1][:-2]) not in planned:
            problems.append(f"{f.path} isn't in the plan. Plan every driver and mid module before writing it.")
        code = "\n".join(b.code for b in f.blocks)
        rank = LAYERS.index(layer) if layer else 2
        for included in INCLUDE.findall(code):
            other = _layer(included)
            if other and LAYERS.index(other) > rank:
                problems.append(f"{f.path} includes {included}, which is a higher layer. Includes only go down.")
            if layer == "app" and other == "driver":
                problems.append(f"{f.path} includes the driver {included}. The app only uses mid modules.")
        if layer != "driver" and RAW_PIN_CALL.search(code):
            problems.append(f"{f.path} touches pins directly ({RAW_PIN_CALL.search(code).group(0)}). Only src/driver may, so go through a mid module.")
        if re.search(r"^\s*#\s*error\b", code, re.M):
            problems.append(f"{f.path} stops the build with #error. Never leave a placeholder: use the agreed value, or a stated default named in one constant and explained in the block description.")
        hollow = stubs(code)
        if hollow:
            problems.append(f"{f.path} has functions that do nothing or always fail: {', '.join(hollow)}. Implement them fully. Never hold a feature back for lack of proof: build on what the person said, and put doubts in the block description.")
        owner = "Software" if layer == "app" or f.path.endswith("main.cpp") else "Electrical"
        if f.owner != owner:
            problems.append(f"{f.path} belongs to {owner}, because the {'app' if owner == 'Software' else layer} layer is theirs.")
    if "driver" not in layers:
        return problems
    owned = {p.removeprefix("BA_PIN_") for m in plan if m.layer == "driver" for p in m.pins}
    orphans = sorted(name for name in pins if name not in owned and not BUILT_IN_LINK.search(name))
    if orphans:
        problems.append(f"No driver in the plan owns these agreed pins: {', '.join(orphans)}. Give each pin to one driver.")
    if pins and not any(m.layer == "driver" for m in plan):
        problems.append("The plan has no driver, but this board has agreed pins. Plan a driver for each peripheral.")
    return problems


SCOPES = {
    "all": (LAYERS, "Write all three layers."),
    "lower": (("driver", "mid"), "Write only the DRIVER and MIDDLEWARE layers, in src/driver and src/mid, with owner Electrical. Software writes the app on top of your mid headers, so make them complete: every event, value and function the requirements need. A placeholder main.cpp lets this build until the app exists."),
    "app": (("app",), "Write only the APP layer, in src/app and src/main.cpp, with owner Software. Use the middleware exactly as its headers in api declare it: never change, copy or redeclare them, and never touch pins. If a function the requirements need is missing, or is only a stub, list it in missing, so Electrical is sent to add it, and call it as soon as it exists. Never leave a requested feature out of the app because the middleware forbids or lacks it: list it in missing instead."),
}
APP_STUB = f"/* {GENERATED_MARK}. Stands in for the app until Software writes it, so the drivers and middleware can be built. */\n#include <Arduino.h>\nvoid setup() {{}}\nvoid loop() {{}}\n"


def _files(root: Path, device: str, folder: str, suffix: str = "") -> dict[str, str]:
    base = root / "firmware" / device
    found = sorted((base / folder).rglob(f"*{suffix}")) if (base / folder).is_dir() else []
    return {p.relative_to(base).as_posix(): p.read_text(encoding="utf-8", errors="replace") for p in found if p.is_file() and GENERATED_MARK not in p.read_text(encoding="utf-8", errors="replace")}


def wiring_ready(state: ProjectState) -> bool:
    """Board code waits for a connection list, drafted or confirmed, when there are parts to wire together."""
    parts = [c for c in state.of_type("component") if c["status"] not in ("rejected", "superseded")]
    nets = [n for n in state.of_type("net") if n["status"] not in ("rejected", "superseded")]
    return len(parts) < 2 or bool(nets)


def has_lower(root: Path, device: str) -> bool:
    """Electrical has written drivers and middleware for this board."""
    return bool(_files(root, device, "src/driver")) and bool(_files(root, device, "src/mid"))


def has_app(root: Path, device: str) -> bool:
    main = root / "firmware" / device / "src" / "main.cpp"
    return bool(_files(root, device, "src/app")) or (main.exists() and GENERATED_MARK not in main.read_text(encoding="utf-8", errors="replace"))


def mid_api(root: Path, device: str) -> dict[str, str]:
    """The middleware headers: the interface Software writes the app against."""
    return _files(root, device, "src/mid", ".h")


def _api_used(ledger: Ledger, device: str) -> tuple[int, dict[str, str]] | None:
    events = ledger.events()
    found = [(i, e["data"]["headers"]) for i, e in enumerate(events) if e["kind"] == "firmware.api_used" and e["data"]["device"] == device]
    return found[-1] if found else None


def api_changed(ledger: Ledger, root: Path, device: str) -> list[str]:
    """Middleware headers that differ from the ones the app was last built against."""
    used = _api_used(ledger, device)
    if not used:
        return []
    now = {path: code_hash(text) for path, text in mid_api(root, device).items()}
    return sorted(p for p in set(now) | set(used[1]) if now.get(p) != used[1].get(p))


def middleware_wanted(ledger: Ledger, device: str) -> list[str]:
    """What Software last said the middleware lacks, unless Electrical has rewritten the middleware since."""
    for e in reversed(ledger.events()):
        if e["kind"] == "firmware.generated" and e["data"]["device"] == device and e["data"].get("scope") in ("lower", "all"):
            return []
        if e["kind"] == "firmware.generated" and e["data"]["device"] == device and e["data"].get("scope") == "app":
            return list(e["data"].get("missing") or [])
    return []


def frozen_problems(ledger: Ledger, root: Path, device: str, files: list[FileOut]) -> list[str]:
    """Once the app is built on a middleware header, changing it needs a change request a person approved,
    or Software asking for something the middleware lacks."""
    used = _api_used(ledger, device)
    if not used or middleware_wanted(ledger, device):
        return []
    index, headers = used
    events = ledger.events()
    proposed = {e["data"]["id"]: e["data"] for e in events if e["kind"] == "change.proposed"}
    approved = {proposed[e["data"]["id"]]["target"] for e in events[index:] if e["kind"] in ("change.approved", "change.auto_approved") and proposed.get(e["data"]["id"], {}).get("type") == "middleware"}
    problems = []
    for f in files:
        if f.path in headers and code_hash(render(f)) != headers[f.path] and f"{device}:{f.path}" not in approved:
            problems.append(f"{f.path} is the agreed interface Software built the app on, so it's frozen. Keep it exactly as it is, or raise_change_request with kind middleware and target {device}:{f.path}, and wait for approval.")
    return problems


def lower_plan(ledger: Ledger, device: str) -> list[ModulePlan]:
    """The drivers and middleware Electrical last planned for this board."""
    for e in reversed(ledger.events()):
        if e["kind"] == "firmware.generated" and e["data"]["device"] == device and e["data"].get("plan") and e["data"].get("scope", "all") in ("lower", "all"):
            return [ModulePlan(**m) for m in e["data"]["plan"] if m["layer"] in ("driver", "mid")]
    # Imported code was never planned by Electrical: the modules already on disk are the plan, so the app can build on them.
    base = ledger.root / "firmware" / device / "src"
    found = []
    for layer, folder in (("driver", "driver"), ("mid", "mid")):
        names = sorted({p.stem for p in (base / folder).glob("*") if p.suffix in (".h", ".hpp", ".cpp", ".c")}) if (base / folder).is_dir() else []
        found += [ModulePlan(layer=layer, name=name, purpose="Existing code imported with the project.", functions=[]) for name in names]
    return found


async def generate(ledger: Ledger, gateway: Gateway, root: Path, device: str, board: str, goal: str, scope: str = "all") -> dict[str, Any]:
    layers, scope_text = SCOPES[scope]
    if scope != "app" and not wiring_ready(ledger.state()):
        return {"written": [], "build": {"ok": False, "ran": False, "errors": [], "detail": "There's no connection list yet, and board code takes its pins only from it. Get the components confirmed and draft_connections first."}, "attempts": 0, "pagesOpened": 0, "findingsSaved": 0}
    if scope == "app" and not has_lower(root, device):
        return {"written": [], "build": {"ok": False, "ran": False, "errors": [], "detail": f"{device} has no drivers and middleware yet. Electrical writes those first, with write_firmware. Ask Electrical with ask_department."}, "attempts": 0, "pagesOpened": 0, "findingsSaved": 0}
    state = ledger.state()
    nets = [n["fields"] for n in state.of_type("net") if n["status"] not in ("rejected", "superseded")]
    session = PageSession(ledger, root, max_pages=14)
    def values(feedback: str) -> dict[str, Any]:
        return {"device": f"{device}, PlatformIO board {board}, {framework} framework", "goal": goal, "connections": nets, "limits": limits_text(state), "pins": pin_defines(ledger.state()), "current_code": outline_code(root, device, goal), "saved_findings": notes_text(ledger.state()), "datasheets": ", ".join(session.library.parts) or "None", "packets": interfaces.summary_for_agents(ledger.state()), "components": sorted(component_names(ledger.state())), "part_skills": part_skills(goal, nets, sorted(component_names(ledger.state())), board, device_config(root, device) or {}), "device_facts": devicefacts.for_agents(ledger.state()), "scope": scope_text, "api": api_text(), "feedback": feedback}

    def api_text() -> str:
        if scope == "app":
            return json.dumps({"modules": [m.model_dump() for m in lower_plan(ledger, device)], "headers": mid_api(root, device)}, ensure_ascii=False)
        wanted = middleware_wanted(ledger, device) if scope == "lower" else []
        if wanted:
            return "Software's app needs these from the middleware. Add every one, keeping existing functions working: " + json.dumps(wanted, ensure_ascii=False) + " Current headers: " + json.dumps(mid_api(root, device), ensure_ascii=False)
        if scope == "lower" and _api_used(ledger, device):
            return "These middleware headers are frozen, because Software's app is built on them. Keep them exactly as they are unless a change request was approved: " + json.dumps(mid_api(root, device), ensure_ascii=False)
        return ""

    attempts: list[dict[str, Any]] = []
    feedback = ""
    board = resolve_board(root, device, board)
    config = device_config(root, device)
    if not config or config["board"] != board:
        write_platformio(root, device, board)
    framework = (device_config(root, device) or {}).get("framework", "arduino")
    interfaces.regenerate(root, state)
    write_pins(root, state, device)
    devicefacts.write_header(root, state, device)
    for attempt in range(3):
        output: FirmwareOut = await gateway.run(agent="firmware", values=values(feedback), output_type=FirmwareOut, tools=[*session.tools(), code_reader(root, device)], request_limit=40)
        merged, kept_problems = merge_unchanged(root, device, output.files)
        output = output.model_copy(update={"files": merged})
        if kept_problems:
            feedback = "\n".join(kept_problems)
            attempts.append({"problem": "documentation", "details": kept_problems})
            continue
        known = valid_note_ids(ledger.state())
        existing = [f["path"] for f in scan_workspace(root, device) if not f["generated"]]
        problems = documentation_problems(output.files) + citation_problems(output.files, known) + component_problems(output.files, component_names(ledger.state())) + layer_problems(output.plan, output.files, existing, pin_defines(ledger.state()) if "driver" in layers else {}, layers, lower_plan(ledger, device) if scope == "app" else None) + (frozen_problems(ledger, root, device, output.files) if "mid" in layers else []) + [p for f in output.files for p in devicefacts.typed_values(ledger.state(), f.path, "\n".join(b.code for b in f.blocks))]
        if problems:
            feedback = "\n".join(problems)
            attempts.append({"problem": "documentation", "details": problems})
            continue
        write_files(root, device, output.files)
        main = root / "firmware" / device / "src" / "main.cpp"
        if scope == "lower" and not has_app(root, device) and framework == "arduino":
            main.parent.mkdir(parents=True, exist_ok=True)
            main.write_text(APP_STUB, encoding="utf-8", newline="\n")
        if output.libraries:
            set_libraries(root, device, output.libraries)
        result = await asyncio.to_thread(build, root, device)  # A build takes a minute, and the app must keep answering.
        attempts.append({"problem": None if result["ok"] else "build", "details": result["errors"]})
        gaps = interfaces.unwired(root, ledger.state(), device) + [p for p in pin_problems(root, ledger.state()) if p.startswith(f"{device}'")]
        if result["ok"] and gaps and attempt == 0:
            feedback = "It compiles, but it isn't complete. Return the complete corrected files.\n" + "\n".join(gaps)
            continue
        if result["ran"]:
            from . import ci, flashing

            ci.record(ledger, f"Firmware:{device}", flashing.source_hash(root / "firmware" / device), result["ok"], result["errors"])
        if result["ok"] or not result["ran"]:
            ledger.append(Actor.system("firmware"), "firmware.generated", device=device, files=[f.path for f in output.files], ok=result["ok"], ran=result["ran"], plan=[m.model_dump() for m in output.plan], scope=scope, missing=output.missing if scope == "app" else [])
            if scope == "app" and result["ok"]:  # From now on the middleware headers are the frozen interface.
                ledger.append(Actor.system("firmware"), "firmware.api_used", device=device, headers={p: code_hash(t) for p, t in mid_api(root, device).items()})
            return {"written": [f.path for f in output.files], "build": result, "attempts": len(attempts), "pagesOpened": len(session.opened), "findingsSaved": len(session.saved)}
        feedback = "The build failed. Return the complete corrected files.\n" + "\n".join(result["errors"])
    details = attempts[-1]["details"] if attempts else []
    return {"written": [], "build": {"ok": False, "ran": True, "errors": details, "detail": "The code was refused three times by the checks listed in errors. This isn't a tool fault, so don't report a BUG: fix what the errors say and call again, or report BLOCKED with what you need."}, "attempts": len(attempts), "pagesOpened": len(session.opened), "findingsSaved": len(session.saved)}


class DescribeOut(BaseModel):
    title: str
    description: str = Field(description="What this file does and why, for someone who has not read the code")
    takes: str = ""
    gives: str = ""


async def describe_file(ledger: Ledger, gateway: Gateway, root: Path, device: str, path: str, owner: str = "Software") -> None:
    """Add one description covering a whole file. The code itself is not changed."""
    target = root / "firmware" / device / path
    text = target.read_text(encoding="utf-8", errors="replace")
    output: DescribeOut = await gateway.run(agent="describe_file", values={"path": path, "source": text[:20000]}, output_type=DescribeOut)
    block = BlockOut(title=output.title, description=output.description, takes=output.takes, gives=output.gives, whole_file=True, code=text.rstrip("\n"))
    target.write_text(render(FileOut(path=path, owner=owner, blocks=[block])), encoding="utf-8", newline="\n")


def build_and_track(ledger: Ledger, root: Path, device: str) -> dict[str, Any]:
    """A failed build opens or repeats a debug session, so the ladder applies."""
    if is_computer(root, device):
        from . import software

        declared = [d["name"] for d in software.setup_view(ledger.events(), device)["dependencies"]]
        result = software.build(root, device, declared)
    else:
        result = build(root, device)
    if result["ran"] and not result["ok"]:
        debugging.open_or_repeat(ledger, "Build failed", "\n".join(result["errors"]) or "Build failed", "code", Actor.system("firmware"), device=device, where=device)
    return result
